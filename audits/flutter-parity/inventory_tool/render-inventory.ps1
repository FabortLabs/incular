# Rebuilds inventory.md from coverage/*.jsonl (the source of truth) and prints
# coverage counts. Run from the repository root:
#   pwsh -File audits/flutter-parity/inventory_tool/render-inventory.ps1
# Each coverage line: file, line, name, package, counterpart, scope (in|out),
# status (scenario|reading|scenario+reading|partial-scenario|partial-reading|
# missing|unchecked|out-of-scope), coverage (text), findings[], scenarios[].
$ErrorActionPreference = 'Stop'
$dir = 'audits/flutter-parity'
$items = @(Get-ChildItem (Join-Path $dir 'coverage') -Filter '*.jsonl' | Sort-Object Name | ForEach-Object {
  Get-Content $_.FullName | Where-Object { $_.Trim() } | ForEach-Object { $_ | ConvertFrom-Json }
})
$dupes = $items | Group-Object { "$($_.file):$($_.line) $($_.name)" } | Where-Object Count -gt 1
if ($dupes) { $dupes | ForEach-Object { Write-Warning "duplicate item: $($_.Name)" } }
$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('# Flutter parity inventory')
$lines.Add('')
$lines.Add('Generated by `inventory_tool/render-inventory.ps1` from `coverage/*.jsonl`; edit the coverage files, not this table. Declarations were AST-extracted from Flutter 3.41.7 (`declarations.jsonl`); getter/setter pairs are one item. `MISSING` means no Incular counterpart was found after a search. Status meanings: `scenario` and `reading` are the methods by which the listed behavior was checked; `partial-*` means only the noted aspects were checked; `out-of-scope` items have no observable widget-layer behavior or belong to Material/Cupertino/embedder/engine concerns, with the reason in the coverage column; `unchecked` gives the reason it was not checked.')
$lines.Add('')
$lines.Add('| Flutter file:line and item | Incular counterpart | Package | Status | Coverage | Findings |')
$lines.Add('| --- | --- | --- | --- | --- | --- |')
foreach ($i in ($items | Sort-Object file, line, name)) {
  $f = if ($i.findings) { ($i.findings -join ', ') } else { '' }
  $cov = ([string]$i.coverage).Replace('|', '\|')
  $lines.Add(('| `{0}:{1}` {2} | {3} | {4} | {5} | {6} | {7} |' -f $i.file, $i.line, $i.name, $i.counterpart, $i.package, $i.status, $cov, $f))
}
[System.IO.File]::WriteAllLines((Join-Path (Resolve-Path $dir) 'inventory.md'), [string[]]$lines)
"items: $($items.Count)"
$items | Group-Object status | Sort-Object Name | ForEach-Object { "{0}: {1}" -f $_.Name, $_.Count }
''
$items | Group-Object package | Sort-Object Name | ForEach-Object {
  $g = $_.Group
  "{0}: total {1}, unchecked {2}" -f $_.Name, $g.Count, @($g | Where-Object status -eq 'unchecked').Count
}
