# Merges fixes/*.jsonl (one object per finding: id, outcome, root_cause, change,
# tests[], harness, api_change, limitations, note, and after orchestrator review
# review/review_note) into fixes.jsonl and regenerates FIXES.md. Findings
# that are accepted in findings.jsonl but have no fix record are listed as open.
# Run from the repository root:
#   pwsh -NoProfile -File audits/flutter-parity/inventory_tool/consolidate-fixes.ps1
$ErrorActionPreference = 'Stop'
$dir = 'audits/flutter-parity'
$findings = @{}
Get-Content (Join-Path $dir 'findings.jsonl') | Where-Object { $_.Trim() } | ForEach-Object {
  $f = $_ | ConvertFrom-Json; $findings[$f.id] = $f
}
$outcomes = @('fixed', 'partial', 'already-fixed', 'invalid', 'duplicate', 'blocked', 'deferred', 'out-of-scope')
$fixes = @(Get-ChildItem (Join-Path $dir 'fixes') -Filter '*.jsonl' | Sort-Object Name | ForEach-Object {
  $file = $_.Name; $n = 0
  Get-Content $_.FullName | ForEach-Object {
    $n++
    if ($_.Trim()) {
      try { $o = $_ | ConvertFrom-Json } catch { throw "${file}:${n}: invalid JSON" }
      # Test-triage notes (ids that are not findings, e.g. "triage:<test>")
      # stay in the group files and .md, but are not finding resolutions.
      if (!$findings.ContainsKey($o.id)) { Write-Host "note (not a finding): ${file}:${n} $($o.id)"; return }
      if ($o.outcome -notin $outcomes) { throw "${file}:${n}: bad outcome '$($o.outcome)'" }
      $o | Add-Member -NotePropertyName group -NotePropertyValue ($file -replace '\.jsonl$', '') -Force
      $o
    }
  }
})
# Later passes revisit earlier groups' findings. When several groups record
# the same id, the record from the latest pass in $passOrder wins and the
# earlier ones are listed in its `superseded` field (group: outcome).
$passOrder = @('orchestrator', 'anim', 'physics', 'text-editing', 'scroll', 'slivers', 'forms', 'layout',
  'gestures', 'navigation', 'semantics', 'animated-widgets', 'paint', 'focus', 'rich-text', 'misc',
  'custom-paint-clip', 'text-selection', 'gestures-api', 'scroll-advanced', 'frame-order', 'text-residual', 'navigation-design', 'semantics-2',
  'animated-widgets-2', 'paint-2', 'text-3', 'scroll-3', 'blockers-render-input', 'blockers-tree')
function PassRank($g) { $i = [array]::IndexOf($passOrder, $g); if ($i -lt 0) { 1000 } else { $i } }
$fixes = @($fixes | Group-Object id | ForEach-Object {
  $ordered = @($_.Group | Sort-Object { PassRank $_.group })
  $winner = $ordered[-1]
  if ($ordered.Count -gt 1) {
    $earlier = @($ordered[0..($ordered.Count - 2)] | ForEach-Object { "$($_.group): $($_.outcome)" })
    $winner | Add-Member -NotePropertyName superseded -NotePropertyValue $earlier -Force
  }
  $winner
})
$sevOrder = @{ P0 = 0; P1 = 1; P2 = 2; P3 = 3 }
$fixes = @($fixes | Sort-Object { $sevOrder[$findings[$_.id].severity] }, id)
[System.IO.File]::WriteAllLines((Join-Path (Resolve-Path $dir) 'fixes.jsonl'), [string[]]@($fixes | ForEach-Object { $_ | ConvertTo-Json -Compress -Depth 10 }))

function Cell($v) { if ($null -eq $v -or "$v" -eq '') { '—' } else { ("$v" -replace '\|', '\|' -replace "`r?`n", ' ') } }
$byId = @{}; $fixes | ForEach-Object { $byId[$_.id] = $_ }
$accepted = @($findings.Values | Where-Object status -eq 'accepted' | Sort-Object { $sevOrder[$_.severity] }, id)
$open = @($accepted | Where-Object { !$byId.ContainsKey($_.id) })
$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('# Flutter parity fixes')
$lines.Add('')
$lines.Add('Generated by `inventory_tool/consolidate-fixes.ps1` from `fixes/*.jsonl`; edit those files (and `fixes/<group>.md` for detail), not this table. The original audit evidence stays in `findings.jsonl` and `findings/<package>.md`. `Review` is the orchestrator''s independent check of the worker''s result.')
$lines.Add('')
$lines.Add('## Outcome counts (accepted findings)')
$lines.Add('')
$lines.Add('| Outcome | P0 | P1 | P2 | P3 | Total |')
$lines.Add('| --- | --- | --- | --- | --- | --- |')
foreach ($o in ($outcomes + 'open')) {
  $set = if ($o -eq 'open') { $open } else { @($accepted | Where-Object { $byId.ContainsKey($_.id) -and $byId[$_.id].outcome -eq $o }) }
  $c = foreach ($s in 'P0', 'P1', 'P2', 'P3') { @($set | Where-Object severity -eq $s).Count }
  $lines.Add(('| {0} | {1} | {2} | {3} | {4} | {5} |' -f $o, $c[0], $c[1], $c[2], $c[3], @($set).Count))
}
$lines.Add('')
$lines.Add('## Resolutions')
$lines.Add('')
$lines.Add('| ID | Sev | Title | Outcome | Review | Change | Tests | Harness | Detail |')
$lines.Add('| --- | --- | --- | --- | --- | --- | --- | --- | --- |')
foreach ($x in $fixes) {
  $f = $findings[$x.id]
  $tests = if ($x.tests) { ($x.tests -join '; ') } else { '' }
  $lines.Add(('| [{0}](findings/{1}.md) | {2} | {3} | {4} | {5} | {6} | {7} | {8} | [{9}](fixes/{9}.md) |' -f $x.id, $f.package, $f.severity, (Cell $f.title), $x.outcome, (Cell $x.review), (Cell $x.change), (Cell $tests), (Cell $x.harness), $x.group))
}
$lines.Add('')
$lines.Add("## Open (no resolution recorded) ($($open.Count))")
$lines.Add('')
if ($open.Count) {
  $lines.Add('| ID | Sev | Title |')
  $lines.Add('| --- | --- | --- |')
  foreach ($f in $open) { $lines.Add(('| [{0}](findings/{1}.md) | {2} | {3} |' -f $f.id, $f.package, $f.severity, (Cell $f.title))) }
} else { $lines.Add('None.') }
[System.IO.File]::WriteAllLines((Join-Path (Resolve-Path $dir) 'FIXES.md'), [string[]]$lines)
"fix records: $($fixes.Count); open: $($open.Count)"
$fixes | Group-Object outcome | ForEach-Object { "{0}: {1}" -f $_.Name, $_.Count }
