#!/usr/bin/env python3
"""Import the pinned Flutter logical/physical keyboard ID and label catalog."""

from pathlib import Path
import argparse
import json
import re
import subprocess

REVISION = "ab2912035e160d9cad6306df307576da6128ebdb"
SOURCE = "packages/flutter/lib/src/services/keyboard_key.g.dart"


def read_pinned(root: Path, filename: str) -> str:
    return subprocess.check_output(
        ["git", "-C", str(root), "show", f"{REVISION}:{filename}"], text=True
    )


def rust_name(name: str) -> str:
    return re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name).upper()


def rust_number(number: int) -> str:
    return f"0x{number:_x}"


def dart_table(source: str, marker: str) -> str:
    start = source.index(marker)
    return source[start:source.index("};", start)]


def generate(source: str) -> str:
    out = [
        "// Generated by audits/flutter-3.50.0-parity/generate-keyboard-catalog.py.",
        "// The data is derived from Flutter, Copyright 2014 The Flutter Authors.",
        "// See flutter_keyboard.LICENSE for the BSD-3-Clause notice.",
        f"// Flutter source revision: {REVISION}.",
        "",
        "use super::{LogicalKeyboardKey, PhysicalKeyboardKey};",
    ]
    for kind, table, labels, width in [
        ("Logical", "_knownLogicalKeys =", "_keyLabels =", "u64"),
        ("Physical", "_knownPhysicalKeys =", "_debugNames =", "u32"),
    ]:
        ty = f"{kind}KeyboardKey"
        keys = {
            name: int(code, 16)
            for name, code in re.findall(
                rf"static const {ty}\s+(\w+)\s*=\s*{ty}\((0x[\da-f]+)\);", source
            )
        }
        known = {
            int(code, 16): name
            for code, name in re.findall(r"(0x[\da-f]+):\s*(\w+),", dart_table(source, table))
        }
        descriptions = {
            int(code, 16): name
            for code, name in re.findall(r"(0x[\da-f]+): '([^']*)',", dart_table(source, labels))
        }
        assert all(keys[name] == code for code, name in known.items())
        assert set(keys.values()) == set(known) == set(descriptions)
        assert len({rust_name(name) for name in keys}) == len(keys)
        out.extend(["", f"impl {ty} {{"])
        for name, code in keys.items():
            out.append(f"    pub const {rust_name(name)}: Self = Self({rust_number(code)});")
        out.append("}")
        out.append("")
        out.append(f"pub(super) static {kind.upper()}: &[({width}, &str)] = &[")
        for code in sorted(known):
            label = json.dumps(descriptions[code], ensure_ascii=False)
            out.append(f"    ({rust_number(code)}, {label}),")
        out.append("];")
    return "\n".join(out) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("flutter_root", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    output = generate(read_pinned(args.flutter_root, SOURCE))
    (args.output / "flutter_keyboard_catalog.rs").write_text(output, encoding="utf-8")
    (args.output / "flutter_keyboard.LICENSE").write_text(
        read_pinned(args.flutter_root, "LICENSE"), encoding="utf-8"
    )


if __name__ == "__main__":
    main()
