//! iOS: cross-compile the app binary, wrap it in an `.app` bundle with a
//! generated `Info.plist`, sign it ad hoc, and run it on a simulator.

use crate::{Options, process};
use std::{
    path::{Path, PathBuf},
    process::{Command, Output},
    time::Duration,
};

const MINIMUM_OS: &str = "16.0";

fn triple(options: &Options) -> &'static str {
    if options.device {
        "aarch64-apple-ios"
    } else if cfg!(target_arch = "x86_64") {
        "x86_64-apple-ios"
    } else {
        "aarch64-apple-ios-sim"
    }
}

fn bundle_id(name: &str) -> String {
    format!(
        "dev.incular.apps.{}",
        process::identifier(name).replace('_', "-")
    )
}

/// Builds an ad-hoc-signed `.app` bundle and returns its path.
pub(crate) fn build(options: &Options) -> Result<PathBuf, String> {
    let triple = triple(options);
    let mut command = Command::new("cargo");
    command
        .args(["build", "-p", &options.package])
        .args(options.target.cargo_args())
        .args([
            "--target",
            triple,
            "--no-default-features",
            "--features",
            &options.features,
        ])
        .env("IPHONEOS_DEPLOYMENT_TARGET", MINIMUM_OS);
    if options.release {
        command.arg("--release");
    }
    process::run(&mut command)?;
    let metadata = process::cargo_metadata()?;
    let profile = if options.release { "release" } else { "debug" };
    let name = options.target.name();
    let executable = process::target_dir(&metadata)
        .join(triple)
        .join(profile)
        .join(options.target.output_subdir())
        .join(name);
    let app = options.out_dir.join("ios").join(format!("{name}.app"));
    if app.exists() {
        std::fs::remove_dir_all(&app)
            .map_err(|error| format!("cannot clear {}: {error}", app.display()))?;
    }
    std::fs::create_dir_all(&app).map_err(|error| error.to_string())?;
    std::fs::copy(&executable, app.join(name))
        .map_err(|error| format!("cannot copy {}: {error}", executable.display()))?;
    process::write(&app.join("Info.plist"), info_plist(name, options.device))?;
    process::run(
        Command::new("codesign")
            .args(["--force", "--sign", "-"])
            .arg(&app),
    )?;
    Ok(app)
}

fn info_plist(name: &str, device: bool) -> String {
    let id = bundle_id(name);
    let platform = if device {
        "iPhoneOS"
    } else {
        "iPhoneSimulator"
    };
    format!(
        r#"<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by `incular`; edits are overwritten on the next build. -->
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleIdentifier</key><string>{id}</string>
    <key>CFBundleExecutable</key><string>{name}</string>
    <key>CFBundleName</key><string>{name}</string>
    <key>CFBundleDisplayName</key><string>{name}</string>
    <key>CFBundlePackageType</key><string>APPL</string>
    <key>CFBundleShortVersionString</key><string>1.0</string>
    <key>CFBundleVersion</key><string>1</string>
    <key>CFBundleInfoDictionaryVersion</key><string>6.0</string>
    <key>CFBundleSupportedPlatforms</key><array><string>{platform}</string></array>
    <key>LSRequiresIPhoneOS</key><true/>
    <key>MinimumOSVersion</key><string>{MINIMUM_OS}</string>
    <key>UIDeviceFamily</key><array><integer>1</integer><integer>2</integer></array>
    <key>UILaunchScreen</key><dict/>
    <key>UIRequiredDeviceCapabilities</key><array><string>arm64</string><string>metal</string></array>
    <key>UISupportedInterfaceOrientations</key>
    <array>
        <string>UIInterfaceOrientationPortrait</string>
        <string>UIInterfaceOrientationLandscapeLeft</string>
        <string>UIInterfaceOrientationLandscapeRight</string>
    </array>
    <key>UIApplicationSupportsIndirectInputEvents</key><true/>
    <key>CADisableMinimumFrameDurationOnPhone</key><true/>
    <key>UIApplicationSceneManifest</key>
    <dict>
        <key>UIApplicationSupportsMultipleScenes</key><false/>
        <key>UISceneConfigurations</key>
        <dict>
            <key>UIWindowSceneSessionRoleApplication</key>
            <array>
                <dict>
                    <key>UISceneConfigurationName</key><string>Default Configuration</string>
                    <key>UISceneDelegateClassName</key><string>IncularSceneDelegate</string>
                </dict>
            </array>
        </dict>
    </dict>
</dict>
</plist>
"#
    )
}

fn launch_installed_app(launch: &mut Command) -> Result<Output, String> {
    // simctl install can return before FrontBoard has registered the bundle.
    let mut delays = [1, 2, 4, 8].into_iter();
    loop {
        match process::output(launch) {
            Err(error) if error.contains("is unknown to FrontBoard") => {
                let Some(delay) = delays.next() else {
                    return Err(error);
                };
                std::thread::sleep(Duration::from_secs(delay));
            }
            result => return result,
        }
    }
}

/// Installs and launches the bundle on the booted simulator, then optionally
/// saves a screenshot and the app's log next to it.
pub(crate) fn run(options: &Options, app: &Path) -> Result<(), String> {
    if options.device {
        return Err(
            "`run ios --device` is not supported yet; install the bundle with Xcode".into(),
        );
    }
    let id = bundle_id(options.target.name());
    process::run(
        Command::new("xcrun")
            .args(["simctl", "install", "booted"])
            .arg(app),
    )?;
    let log_path = options
        .screenshot
        .as_ref()
        .map(|screenshot| screenshot.with_extension("log"));
    let mut launch = Command::new("xcrun");
    launch.args(["simctl", "launch", "--terminate-running-process"]);
    if let Some(log_path) = &log_path {
        if let Some(parent) = log_path.parent() {
            std::fs::create_dir_all(parent).map_err(|error| error.to_string())?;
        }
        launch.arg(format!("--stdout={}", log_path.display()));
        launch.arg(format!("--stderr={}", log_path.display()));
    }
    // Prints `<bundle id>: <pid>`; simulator apps are host processes.
    let launched = launch_installed_app(launch.args(["booted", &id]))?;
    let pid = String::from_utf8_lossy(&launched.stdout)
        .rsplit(':')
        .next()
        .map(|pid| pid.trim().to_owned())
        .unwrap_or_default();
    let Some(screenshot) = &options.screenshot else {
        return Ok(());
    };
    std::thread::sleep(Duration::from_secs(options.wait_seconds));
    let running = !pid.is_empty()
        && Command::new("kill")
            .args(["-0", &pid])
            .status()
            .is_ok_and(|status| status.success());
    process::run(
        Command::new("xcrun")
            .args(["simctl", "io", "booted", "screenshot"])
            .arg(screenshot),
    )?;
    let _ = Command::new("xcrun")
        .args(["simctl", "terminate", "booted", &id])
        .status();
    if running {
        Ok(())
    } else {
        Err(format!(
            "{id} exited before the screenshot; see {}",
            screenshot.with_extension("log").display()
        ))
    }
}
