//! Stable keyboard IDs for Flutter interoperability. These values do not
//! replace the platform-neutral keyboard types used for native dispatch.

use std::borrow::Cow;

use indexmap::IndexSet;

#[path = "flutter_keyboard_catalog.rs"]
mod catalog;

/// A physical key identified by its USB HID usage.
#[derive(Clone, Copy, Debug, Eq, Hash, Ord, PartialEq, PartialOrd)]
pub struct PhysicalKeyboardKey(u32);

impl PhysicalKeyboardKey {
    #[must_use]
    pub const fn new(usb_hid_usage: u32) -> Self {
        Self(usb_hid_usage)
    }

    #[must_use]
    pub const fn usb_hid_usage(self) -> u32 {
        self.0
    }

    #[must_use]
    pub fn find_key_by_code(usb_hid_usage: u32) -> Option<Self> {
        let index = catalog::PHYSICAL
            .binary_search_by_key(&usb_hid_usage, |(code, _)| *code)
            .ok()?;
        Some(Self(catalog::PHYSICAL[index].0))
    }

    #[must_use]
    pub fn debug_name(self) -> Option<Cow<'static, str>> {
        if !cfg!(debug_assertions) {
            return None;
        }
        Some(
            catalog::PHYSICAL
                .binary_search_by_key(&self.0, |(code, _)| *code)
                .ok()
                .map_or_else(
                    || Cow::Owned(format!("Key with ID 0x{:08x}", self.0)),
                    |index| Cow::Borrowed(catalog::PHYSICAL[index].1),
                ),
        )
    }
}

/// A logical key identified by its stable Flutter key ID.
#[derive(Clone, Copy, Debug, Eq, Hash, Ord, PartialEq, PartialOrd)]
pub struct LogicalKeyboardKey(u64);

impl LogicalKeyboardKey {
    pub const VALUE_MASK: u64 = 0xffff_ffff;
    pub const PLANE_MASK: u64 = 0xff_0000_0000;
    pub const UNICODE_PLANE: u64 = 0;
    pub const UNPRINTABLE_PLANE: u64 = 0x01_0000_0000;
    pub const FLUTTER_PLANE: u64 = 0x02_0000_0000;
    pub const START_OF_PLATFORM_PLANES: u64 = 0x11_0000_0000;
    pub const ANDROID_PLANE: u64 = 0x11_0000_0000;
    pub const FUCHSIA_PLANE: u64 = 0x12_0000_0000;
    pub const IOS_PLANE: u64 = 0x13_0000_0000;
    pub const MACOS_PLANE: u64 = 0x14_0000_0000;
    pub const GTK_PLANE: u64 = 0x15_0000_0000;
    pub const WINDOWS_PLANE: u64 = 0x16_0000_0000;
    pub const WEB_PLANE: u64 = 0x17_0000_0000;
    pub const GLFW_PLANE: u64 = 0x18_0000_0000;

    #[must_use]
    pub const fn new(key_id: u64) -> Self {
        Self(key_id)
    }

    #[must_use]
    pub const fn key_id(self) -> u64 {
        self.0
    }

    #[must_use]
    pub fn find_key_by_key_id(key_id: u64) -> Option<Self> {
        Self(key_id).known_name().map(|_| Self(key_id))
    }

    fn known_name(self) -> Option<&'static str> {
        let index = catalog::LOGICAL
            .binary_search_by_key(&self.0, |(code, _)| *code)
            .ok()?;
        Some(catalog::LOGICAL[index].1)
    }

    fn unicode_label(self) -> Option<String> {
        let character = char::from_u32(u32::try_from(self.0).ok()?)?;
        Some(character.to_uppercase().collect())
    }

    /// Printable labels are the uppercased Unicode value, regardless of
    /// whether that code is present in the pre-defined name catalog.
    #[must_use]
    pub fn key_label(self) -> Cow<'static, str> {
        self.unicode_label().map_or_else(
            || Cow::Borrowed(self.known_name().unwrap_or("")),
            Cow::Owned,
        )
    }

    #[must_use]
    pub fn debug_name(self) -> Option<Cow<'static, str>> {
        if !cfg!(debug_assertions) {
            return None;
        }
        Some(self.known_name().map_or_else(
            || {
                Cow::Owned(self.unicode_label().map_or_else(
                    || format!("Key with ID 0x{:011x}", self.0),
                    |label| format!("Key {label}"),
                ))
            },
            Cow::Borrowed,
        ))
    }

    #[must_use]
    pub fn is_control_character(label: &str) -> bool {
        super::is_control_key_label(label)
    }

    #[must_use]
    pub const fn is_autogenerated(self) -> bool {
        (self.0 & Self::PLANE_MASK) >= Self::START_OF_PLATFORM_PLANES
    }

    /// Abstract synonyms of a sided modifier. Abstract keys themselves
    /// have no synonyms in this direction.
    #[must_use]
    pub const fn synonyms(self) -> &'static [Self] {
        match self {
            Self::SHIFT_LEFT | Self::SHIFT_RIGHT => &[Self::SHIFT],
            Self::CONTROL_LEFT | Self::CONTROL_RIGHT => &[Self::CONTROL],
            Self::ALT_LEFT | Self::ALT_RIGHT => &[Self::ALT],
            Self::META_LEFT | Self::META_RIGHT => &[Self::META],
            _ => &[],
        }
    }

    fn concrete_synonyms(self) -> &'static [Self] {
        match self {
            Self::SHIFT => &[Self::SHIFT_LEFT, Self::SHIFT_RIGHT],
            Self::CONTROL => &[Self::CONTROL_LEFT, Self::CONTROL_RIGHT],
            Self::ALT => &[Self::ALT_LEFT, Self::ALT_RIGHT],
            Self::META => &[Self::META_LEFT, Self::META_RIGHT],
            _ => &[],
        }
    }

    /// Replaces sided modifiers with their abstract keys, retaining the
    /// first occurrence of each resulting key.
    #[must_use]
    pub fn collapse_synonyms(keys: impl IntoIterator<Item = Self>) -> IndexSet<Self> {
        replace_synonyms(keys, Self::synonyms)
    }

    /// Replaces abstract modifiers with their concrete left and right keys.
    #[must_use]
    pub fn expand_synonyms(keys: impl IntoIterator<Item = Self>) -> IndexSet<Self> {
        replace_synonyms(keys, Self::concrete_synonyms)
    }
}

fn replace_synonyms(
    keys: impl IntoIterator<Item = LogicalKeyboardKey>,
    replacements: impl Fn(LogicalKeyboardKey) -> &'static [LogicalKeyboardKey],
) -> IndexSet<LogicalKeyboardKey> {
    let mut result = IndexSet::new();
    for key in keys {
        let values = replacements(key);
        if values.is_empty() {
            result.insert(key);
        } else {
            result.extend(values.iter().copied());
        }
    }
    result
}
